import { z } from 'zod';
import { keccak256, toHex } from 'viem';
import { termSheetSchema, type TermSheet } from './index.js';

/**
 * Normalizes agreement text deterministically across all environments:
 * 1. Replaces all Windows CRLF (\r\n) and classic Mac (\r) linebreaks with Unix LF (\n)
 * 2. Trims trailing whitespace from each line
 * 3. Trims leading and trailing whitespace from the full document
 */
export function canonicalizeAgreementText(text: string): string {
  if (!text) return '';
  return text
    .replace(/\r\n|\r/g, '\n')
    .split('\n')
    .map((line) => line.trimEnd())
    .join('\n')
    .trim();
}

/**
 * Computes the 32-byte Keccak256 hash of the canonicalized agreement text.
 * This hash matches the bytes32 agreementHash anchored on-chain in LoanPool.
 */
export function computeAgreementHash(canonicalText: string): `0x${string}` {
  return keccak256(toHex(canonicalText));
}

export const agreementFieldSourceSchema = z.enum(['text', 'default', 'missing']);
export type AgreementFieldSource = z.infer<typeof agreementFieldSourceSchema>;

export interface ParsedField<T> {
  value?: T;
  source: AgreementFieldSource;
  quote?: string;
}

export interface UnsupportedClause {
  clause: string;
  quote: string;
  reason: string;
}

export interface UnresolvedMerchant {
  name: string;
  quote?: string;
}

export interface ResolvedMerchant {
  name: string;
  address: `0x${string}`;
  capEth?: string;
  capWei?: string;
  quote?: string;
}

export interface AgreementParseResult {
  rawText: string;
  canonicalText: string;
  agreementHash: `0x${string}`;
  parser: 'llm' | 'deterministic';
  fields: {
    targetEth: ParsedField<string>;
    currency: ParsedField<string>;
    aprPercent: ParsedField<number>;
    durationDays: ParsedField<number>;
    fundingDays: ParsedField<number>;
    spendCapEth: ParsedField<string>;
    defaultQuorumPercent: ParsedField<number>;
    gracePeriodDays: ParsedField<number>;
  };
  terms: TermSheet | null;
  resolvedMerchants: ResolvedMerchant[];
  unresolvedMerchants: UnresolvedMerchant[];
  missingFields: string[];
  unsupportedClauses: UnsupportedClause[];
  summary: string;
  isValid: boolean;
  validationErrors: string[];
}

export const parseAgreementRequestSchema = z.object({
  agreementText: z.string().min(10).max(20000),
  acceptedDefaults: z.record(z.string(), z.any()).optional(),
  borrowerAddress: z.string().regex(/^0x[a-fA-F0-9]{40}$/).optional()
});
export type ParseAgreementRequest = z.infer<typeof parseAgreementRequestSchema>;

/**
 * Deterministically reverse-renders a plain-English agreement summary
 * strictly from extracted/validated smart contract parameters.
 * Never generated by LLMs to prevent hallucination.
 */
export function reverseRenderSummary(params: {
  targetEth?: string;
  aprPercent?: number;
  durationDays?: number;
  fundingDays?: number;
  spendCapEth?: string;
  quorumPercent?: number;
  gracePeriodDays?: number;
  merchants?: Array<{ name: string; capEth?: string }>;
}): string {
  const parts: string[] = [];

  const target = params.targetEth ? `${params.targetEth} ETH` : '[Principal Target Unspecified]';
  const duration = params.durationDays !== undefined ? `${params.durationDays} days` : '[Duration Unspecified]';
  const apr = params.aprPercent !== undefined ? `${params.aprPercent}%` : '[Interest Rate Unspecified]';
  parts.push(`This loan agreement establishes a multi-lender credit facility of ${target} for a tenure of ${duration} at a fixed annual interest rate of ${apr}.`);

  const funding = params.fundingDays !== undefined ? `${params.fundingDays} days` : '7 days';
  parts.push(`The syndicate funding window is open for ${funding} from deployment.`);

  const spendCap = params.spendCapEth ? `${params.spendCapEth} ETH` : '[Spend Cap Unspecified]';
  if (params.merchants && params.merchants.length > 0) {
    const merchantList = params.merchants
      .map((m) => (m.capEth ? `${m.name} (cap: ${m.capEth} ETH)` : m.name))
      .join(', ');
    parts.push(`Borrower drawdowns are capped at ${spendCap} and strictly restricted on-chain to approved verified suppliers: ${merchantList}.`);
  } else {
    parts.push(`Borrower drawdowns are restricted to a maximum aggregate limit of ${spendCap}.`);
  }

  const quorum = params.quorumPercent !== undefined ? `${params.quorumPercent}%` : '50.01%';
  const grace = params.gracePeriodDays !== undefined ? `${params.gracePeriodDays} days` : '3 days';
  parts.push(`In the event of overdue repayment after maturity, default declaration requires a capital-weighted lender voting quorum of at least ${quorum} following an on-chain grace period of ${grace}.`);

  return parts.join(' ');
}
